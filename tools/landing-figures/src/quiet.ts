/** Bundles the very same scene against the decorative runner, with no framed input or narration. */
export function quietTourScript(figure: Figure, format: 'esm' | 'iife'): string {
  const scene = readFileSync(
    resolve(import.meta.dirname, 'figures', `${figure.id}.tour.js`),
    'utf8',
  )
    .replace("from './tour.js'", "from '../quiet-tour.ts'")
    .replace('export function playTour', 'function playTour');
  const source = `${scene}
const DATA = ${JSON.stringify(figure.tour)};
${format === 'esm' ? 'export function play(root){ return playTour(root, DATA); }' : "const play = root => playTour(root, DATA); window.quietTour = play(document.querySelector('[data-quiet]'));"}
play.license = ${JSON.stringify(KIT_NOTICE)};`;
  return buildSync({
    stdin: { contents: source, resolveDir: resolve(import.meta.dirname, 'figures'), loader: 'js' },
    bundle: true,
    format,
    minify: true,
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    write: false,
  }).outputFiles[0]!.text;
}

/** Transparent figure; the preview alone supplies the page background. No plate or page copy. */
export function quietPage(figure: Figure, theme: Theme): string {
  return `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${figure.id} quiet ${theme}</title><style>${quietBaseCss}\n${figure.css}\n${quietCss}\nbody{margin:0;background:${theme === 'light' ? '#f4f5f9' : '#0e1016'}}.iso-figure{margin:0;width:${figure.width}px}</style><div class="iso iso-figure" data-quiet data-theme="${theme}" aria-hidden="true"><div data-stage>${figure.svg}</div></div><script>${quietTourScript(figure, 'iife')}</script></html>`;
}

export const quietStillFile = (figure: Figure, theme: Theme) => `${figure.id}-quiet-${theme}.png`;
const camel = (id: string) => id.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
const HEADER = '// Generated by tools/landing-figures. Do not edit.\n';
export function quietFiles(figures: Figure[]): Map<string, string> {
  const files = new Map<string, string>();
  files.set(
    `${OUT_DIR}/quiet-figure.ts`,
    `${HEADER}
export interface QuietFigure { id: string; width: number; height: number; svg: string; css: string; stills: { light: string; dark: string } }
export interface QuietTourControl { setPaused(paused: boolean): void; stop(): void }
export const QUIET_TOUR_SPEED = ${QUIET_TOUR_SPEED};
export const quietFigureCss = ${JSON.stringify(quietBaseCss + '\n' + quietCss)};
`,
  );
  for (const figure of figures) {
    const { id, width, height, svg, css } = figure;
    files.set(
      `${OUT_DIR}/${id}-quiet.ts`,
      `${HEADER}import 'server-only';\nimport type { QuietFigure } from './quiet-figure';\nexport const ${camel(id)}Quiet = ${JSON.stringify({ id, width, height, svg, css, stills: Object.fromEntries((['light', 'dark'] as const).map((theme) => [theme, `${STILL_URL_DIR}/${quietStillFile(figure, theme)}`])) })} satisfies QuietFigure;\n`,
    );
    files.set(`${OUT_DIR}/${id}-quiet-tour.js`, `${HEADER}${quietTourScript(figure, 'esm')}`);
  }
  files.set(
    `${OUT_DIR}/quiet-tours.ts`,
    `${HEADER}import type { QuietTourControl } from './quiet-figure';\nexport { QUIET_TOUR_SPEED } from './quiet-figure';\nexport const quietTours: Record<string, () => Promise<{play(root: HTMLElement): QuietTourControl}>> = {\n${figures.map((f) => `  '${f.id}': () => import('./${f.id}-quiet-tour.js'),`).join('\n')}\n};\n`,
  );
  files.set(
    `${OUT_DIR}/quiet.ts`,
    `${HEADER}export { quietFigureCss, QUIET_TOUR_SPEED, type QuietFigure, type QuietTourControl } from './quiet-figure';\n${figures.map((f) => `export { ${camel(f.id)}Quiet } from './${f.id}-quiet';`).join('\n')}\n`,
  );
  return files;
}
