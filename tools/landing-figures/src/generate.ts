import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildSync } from 'esbuild';
import { ISO_CSS } from './kit.ts';
import { buildSplittingLine } from './figures/splitting-line.mjs';
import { story } from './story.ts';

/** Where the generated modules live in the web app, relative to the repository root. */
export const OUT_DIR = 'apps/web/src/components/landing-figures/generated';
/** Where each figure's light still is served from, and where that is in the web app's public folder. */
export const STILL_URL_DIR = '/landing-figures';
export const STILL_DIR = `apps/web/public${STILL_URL_DIR}`;
/** The still's size: an Open Graph link preview. */
export const STILL_SIZE = { width: 1200, height: 630 } as const;

const PACKAGE_DIR = resolve(import.meta.dirname, '..');
const FIGURES_DIR = resolve(import.meta.dirname, 'figures');
const KIT_LICENSE = readFileSync(resolve(PACKAGE_DIR, 'vendor/anatomy/LICENSE'), 'utf8').trim();
/**
 * The kit's MIT notice, shipped inside every tour chunk. Next's minifier strips comments, legal ones
 * included, so the chunk carries it as a property of its `play` export, which it must keep.
 */
export const KIT_NOTICE = `Anatomy kit (https://github.com/wheresryan22/anatomy)\n\n${KIT_LICENSE}`;

const HEADER =
  '// Generated by tools/landing-figures (`pnpm --filter @splitbook/landing-figures build`). Do not edit.\n';

export type Figure = ReturnType<typeof buildSplittingLine>;

export function buildFigures(): Figure[] {
  return [buildSplittingLine(story())];
}

const camel = (id: string) => id.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

/**
 * A figure's live tour, bundled with the kit functions it uses and its data. As an ES module it
 * exports `play(root)` for the web app; as a classic script it plays the first `.iso-figure` in
 * a preview page straight away.
 */
export function tourScript(figure: Figure, format: 'esm' | 'iife'): string {
  const data = `const DATA = ${JSON.stringify(figure.tour)};`;
  const call =
    format === 'esm'
      ? `export function play(root) {\n  return playTour(root, DATA);\n}\nplay.license = ${JSON.stringify(KIT_NOTICE)};`
      : "playTour(document.querySelector('.iso-figure'), DATA);";
  const result = buildSync({
    stdin: {
      contents: `import { playTour } from './${figure.id}.tour.js';\n${data}\n${call}\n`,
      resolveDir: FIGURES_DIR,
      sourcefile: `${figure.id}.tour-entry.js`,
      loader: 'js',
    },
    absWorkingDir: PACKAGE_DIR,
    bundle: true,
    format,
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    write: false,
  });
  return result.outputFiles[0]!.text;
}

const stillFile = (figure: Figure) => `${figure.id}-light.png`;
export const stillPath = (figure: Figure) => `${STILL_DIR}/${stillFile(figure)}`;

/**
 * The web app's view of the figures:
 * - `figure.ts`: the figure type and one shared stylesheet (the kit's light and dark tokens);
 * - `<id>.ts`: per figure, server only, its static drawing, its words and its still;
 * - `<id>-tour.js`: its live tour, a client chunk loaded near the screen;
 * - `tours.ts`: the loaders for those chunks, the only figure code in the client bundle;
 * - `index.ts`: re-exports for the server.
 */
export function generatedFiles(figures: Figure[]): Map<string, string> {
  const files = new Map<string, string>();
  files.set(
    `${OUT_DIR}/figure.ts`,
    `${HEADER}
/** A landing figure, drawn once at build time: the same markup in light and dark. */
export interface LandingFigure {
  id: string;
  /** Its number on the page: Fig 1, Fig 2… */
  number: number;
  title: string;
  /** What the drawing shows, for assistive technology (role="img"). */
  label: string;
  width: number;
  height: number;
  /** The figure's SVG at rest, styled by figureCss and its own css under an .iso wrapper. */
  svg: string;
  css: string;
  /** The plate's readout before the live tour runs. */
  readout: string;
  /** The legend under the plate: each key's mark and words. */
  legend: { mark: 'bin' | 'positive' | 'negative' | 'lamp'; label: string }[];
  caption: string;
  /** The light still the tour shows under reduced motion, as a link preview image. */
  still: { src: string; width: number; height: number; alt: string };
}

/** The kit's styles; a wrapper with class "iso" picks dark, or light with data-theme="light". */
export const figureCss = ${JSON.stringify(ISO_CSS)};
`,
  );
  for (const figure of figures) {
    const data = {
      id: figure.id,
      number: figure.number,
      title: figure.title,
      label: figure.label,
      width: figure.width,
      height: figure.height,
      svg: figure.svg,
      css: figure.css,
      readout: figure.readout,
      legend: figure.legend,
      caption: figure.caption,
      still: {
        src: `${STILL_URL_DIR}/${stillFile(figure)}`,
        ...STILL_SIZE,
        alt: figure.still,
      },
    };
    files.set(
      `${OUT_DIR}/${figure.id}.ts`,
      `${HEADER}import 'server-only';
import type { LandingFigure } from './figure';

export const ${camel(figure.id)}: LandingFigure = ${JSON.stringify(data)};
`,
    );
    files.set(
      `${OUT_DIR}/${figure.id}-tour.js`,
      `${HEADER}// ${figure.title}: its live tour, with code from the Anatomy kit (MIT); its notice ships as
// play.license.
${tourScript(figure, 'esm')}`,
    );
  }
  files.set(
    `${OUT_DIR}/tours.ts`,
    `${HEADER}
/** Each figure's live tour, loaded on demand; \`play\` returns a function that stops it. */
export const tours: Record<string, () => Promise<{ play(root: HTMLElement): () => void }>> = {
${figures.map((f) => `  '${f.id}': () => import('./${f.id}-tour.js'),`).join('\n')}
};
`,
  );
  files.set(
    `${OUT_DIR}/index.ts`,
    `${HEADER}export { figureCss, type LandingFigure } from './figure';\n${figures.map((f) => `export { ${camel(f.id)} } from './${f.id}';`).join('\n')}\n`,
  );
  return files;
}
